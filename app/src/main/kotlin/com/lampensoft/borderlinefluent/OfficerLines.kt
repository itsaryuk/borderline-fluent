/** The language question's topic (PRD §5): asked once, never a cover fact. */
const val HOWLANG = "howlang"

/** PRD §5: a visitor whose passport country doesn't speak the desk's language is asked how they know it; never at home. */
fun asksHowLang(kind: TripKind, lang: String, nationality: Nationality) = kind == TripKind.ARRIVAL && lang !in nationality.languages

/** The officer's reaction sets to an implant mention (`implant.<tone>.n`). */
val IMPLANT_TONES = listOf("amused", "curious", "sceptical", "impressed")

/** One tone per officer, from its persona. ponytail: thresholds are guesses; more sets per tone after playtests (PRD §5). */
fun implantTone(p: Persona) = when {
    p.strictness > 0.7 -> "sceptical"
    p.tolerance > 0.8 -> "amused"
    p.patience > 0.85 -> "impressed"
    else -> "curious"
}

/** A fixed statement prefix followed by one question, both catalog ids. */
data class Move(val prefix: String?, val question: String, val reask: Boolean = false)

/** Per-interview topic and wording selection, independent of rendering. */
/** [arrival]: a visitor's interview, asked in the `.visit` wordings where the catalog has them. */
/** [howlang]: ask [HOWLANG] once after a good first answer ([asksHowLang]); [tone]: the implant reaction set ([implantTone]). */
/** [sawHelp]: the first question after the passport opens with [ENCOUNTER_SAW] (the traveller helped in the queue). */
/**
 * [taint]: a planted motif ([Poison.deskTaint]) whose `taint.<motif>` statement replaces the first plain acknowledgement
 * (`ack`, `ack.curt`), so it ranks below every other prefix, [sawHelp] included; said once per desk.
 */
class Desk(private val rng: Random = Random.Default, private val topics: List<String> = OFFICER_TOPICS, private val arrival: Boolean = false,
           howlang: Boolean = false, private val tone: String = "curious", private val sawHelp: Boolean = false, homeArrival: Boolean = false,
           private var taint: Motif? = null) {
    private val groups = OFFICER_LINES.getValue("en").keys.groupBy { it.substringBeforeLast('.') }
    private val used = mutableMapOf<String, Int>()
    private val previous = mutableMapOf<String, String>()
    private val done = mutableSetOf<String>()
    private val reasks = mutableMapOf<String, Int>()
    private val exactAsked = mutableSetOf<String>()
    var topic: String? = null; private set
    var lastQuestion: String? = null; private set
    private val shots = mutableSetOf<String>() // one-shot topics ([oneShot]), asked or not
    private val due = mutableMapOf<String, IntRange>() // one-shot topics not asked yet → after which topic answers
    private var answers = 0 // replies to topic questions so far: a one-shot question needs a good one in its range
    init { if (howlang) oneShot(HOWLANG, 1..1) }

    /**
     * A question asked at most once, outside the cover topics: right after the [after]th topic answer when that answer
     * was good (no re-ask, contradiction or tell); dropped once the answers pass [after]. Its question is `ask.<topic>`
     * (a catalog group, else the bare id the game renders), its acknowledgement `ack.<topic>` where the catalog has one.
     */
    fun oneShot(topic: String, after: IntRange) { shots += topic; due[topic] = after }
    private val fixedArrival = if (homeArrival) ArrayDeque(listOf("arrivalnews", "phone")) else ArrayDeque<String>()
    init { if (homeArrival) shots.addAll(listOf("arrivalnews", "phone")) }
    private var turn = 0
    private var implantAt = -2 // the turn of the last implant reaction: at most one per two turns

    /** [group]'s visitor wording ("ask.days" → "ask.days.visit") for an [arrival], where one exists. */
    private fun worded(group: String) = if (arrival && "$group.visit" in groups) "$group.visit" else group

    /** The first-contradiction group naming the document that holds [fact] ("press.arrival.days" for a visitor), else "press.first". */
    private fun documentPress(fact: FactId?): String {
        val key = when (fact) {
            FactId.DAYS -> "days"; FactId.STAY -> "stay"; FactId.PURPOSE -> "purpose"; FactId.FROM -> "from"
            FactId.HOST -> "host"; FactId.NAME_BORN, FactId.HOME -> "passport"; else -> return "press.first"
        }
        return listOfNotNull("press.arrival.$key".takeIf { arrival }, "press.$key").firstOrNull { it in groups } ?: "press.first"
    }

    /** Least-used wording, with random ties and no consecutive repeat when alternatives exist. */
    fun pick(group: String): String {
        val ids = groups.getValue(group)
        val eligible = if (ids.size > 1) ids.filter { it != previous[group] } else ids
        val least = eligible.minOf { used[it] ?: 0 }
        return eligible.filter { (used[it] ?: 0) == least }.random(rng).also {
            used[it] = (used[it] ?: 0) + 1
            previous[group] = it
        }
    }

    /** [first]: greeting; [passportPending]: still waiting; [handover]: just received the passport or finished small talk. */
    fun next(cues: List<Cue>, cueFact: FactId?, covered: Set<FactId>, passportPending: Boolean, first: Boolean,
             handover: Boolean, curt: Boolean): Move {
        fun move(prefix: String?, question: String, reask: Boolean = false): Move {
            lastQuestion = question
            topic = question.split('.').let { if (it[0] == "ask" || it[0] == "exact") it[1] else null }
            return Move(prefix, question, reask)
        }
        fun nextTopic() = topics.firstOrNull { it !in done && topicFact(it) !in covered }
        fun ask(t: String?) = pick(if (t == null) "follow" else worded("ask.$t"))
        turn++
        if (first) return move(null, pick("greet"))
        val saw = handover && sawHelp
        if (passportPending) return move(null, pick(if (Cue.PASSPORT_2 in cues) "passport.why" else "passport.again"), reask = true)
        if (Cue.GLITCH in cues) return move(pick("glitch"),
            lastQuestion?.takeUnless { it.startsWith("exact.") } ?: ask(topic ?: nextTopic()), reask = true)
        if (topic != null && topic !in shots) answers++
        val reacts = turn - implantAt >= 2
        val cue = cues.filter { it != Cue.PAUSE && it != Cue.PASSPORT_1 && it != Cue.PASSPORT_2 && (it != Cue.IMPLANT || reacts) }.maxByOrNull { it.ordinal }
        if (cue == Cue.IMPLANT) implantAt = turn
        val prefix = when (cue) {
            Cue.TRICK -> "trick"
            // A lie about the queue: one sceptical line, no press (the meter already moved).
            Cue.CONTRA_AGAIN -> if (cueFact == FactId.ENCOUNTER) ENCOUNTER_LIE else "press.again"
            Cue.CONTRA_FIRST -> if (cueFact == FactId.ENCOUNTER) ENCOUNTER_LIE else documentPress(cueFact)
            Cue.WRONG_LANGUAGE -> "wronglang"
            Cue.UNCLEAR -> if (curt) "unclear.curt" else "unclear"
            Cue.ODD -> "odd"
            Cue.DODGE -> if (curt) "dodge.curt" else "dodge"
            Cue.SILENCE_2 -> if (curt) "silence.curt" else "silence.2"
            Cue.SILENCE_1 -> "silence.1"
            Cue.IMPLANT -> "implant.$tone"
            Cue.LOOK, Cue.TELL -> null
            else -> when {
                saw -> ENCOUNTER_SAW
                handover -> "ack"
                topic in shots && "ack.$topic" in groups -> "ack.$topic"
                curt -> "ack.curt"
                else -> "ack"
            }
        }?.let { g -> taint?.takeIf { g == "ack" || g == "ack.curt" }?.let { taint = null; "taint.${it.id}" } ?: g }?.let { pick(it) }
        if (fixedArrival.isNotEmpty()) return move(prefix, pick("ask.${fixedArrival.removeFirst()}"))
        val contra = (Cue.CONTRA_FIRST in cues || Cue.CONTRA_AGAIN in cues) && cueFact != FactId.ENCOUNTER
        val reask = cues.any { it in setOf(Cue.TRICK, Cue.WRONG_LANGUAGE, Cue.UNCLEAR, Cue.ODD,
            Cue.DODGE, Cue.SILENCE_1, Cue.SILENCE_2) }
        val countedReask = contra || cues.any { it in setOf(Cue.WRONG_LANGUAGE,
            Cue.UNCLEAR, Cue.ODD, Cue.DODGE, Cue.SILENCE_1, Cue.SILENCE_2) }
        // Judge fact attribution need not match the question the traveler just answered.
        if (!reask && !contra && Cue.PASSPORT_1 !in cues && Cue.PASSPORT_2 !in cues) {
            topic?.let { done += it }
        }
        topic?.let { current ->
            if (countedReask) {
                val count = reasks[current] ?: 0
                if (count >= 2) {
                    done += current
                    return move(prefix, ask(nextTopic()))
                }
                reasks[current] = count + 1
            }
        }
        val calm = Cue.GOOD in cues && !reask && !contra && Cue.TELL !in cues
        due.entries.firstOrNull { calm && answers in it.value }?.key?.let { shot ->
            due.remove(shot)
            return move(prefix, if ("ask.$shot" in groups) pick("ask.$shot") else "ask.$shot")
        }
        due.entries.removeAll { answers >= it.value.last } // past its range: never asked
        // A one-shot question is asked once: after any answer to it, Desk moves on (a placed contradiction is
        // still pressed on its itinerary fact below).
        val stay = topic.takeIf { it !in shots }
        val target = when {
            contra -> factTopic(cueFact)?.takeIf {
                it in topics && (topic == null || topic in shots || it == topic) && (cueFact != FactId.NAME_BORN || topic == "born")
            } ?: stay ?: nextTopic()
            reask -> stay ?: nextTopic()
            else -> nextTopic()
        }
        val pressed = topic !in shots || (contra && target == factTopic(cueFact)) // a fresh topic gets its plain wording
        val exact = pressed && !contra && Cue.GOOD !in cues && target != null &&
            worded("exact.$target") in groups && target == topic && (Cue.UNCLEAR in cues || Cue.DODGE in cues)
        if (exact && !exactAsked.add(target)) {
            done += target
            return move(prefix, ask(nextTopic()))
        }
        val question = if (exact) pick(worded("exact.$target")) else ask(target)
        return move(prefix, question, reask = reask && !contra && !handover && topic !in shots)
    }
}

