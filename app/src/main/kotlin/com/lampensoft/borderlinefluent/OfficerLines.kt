/** A fixed statement prefix followed by one question, both catalog ids. */
data class Move(val prefix: String?, val question: String, val reask: Boolean = false)

/** Per-interview topic and wording selection, independent of rendering. */
class Desk(private val rng: Random = Random.Default, private val topics: List<String> = OFFICER_TOPICS) {
    private val groups = OFFICER_LINES.getValue("en").keys.groupBy { it.substringBeforeLast('.') }
    private val used = mutableMapOf<String, Int>()
    private val previous = mutableMapOf<String, String>()
    var topic: String? = null; private set
    var lastQuestion: String? = null; private set

    /** Least-used wording, with random ties and no consecutive repeat when alternatives exist. */
    fun pick(group: String): String {
        val ids = groups.getValue(group)
        val eligible = if (ids.size > 1) ids.filter { it != previous[group] } else ids
        val least = eligible.minOf { used[it] ?: 0 }
        return eligible.filter { (used[it] ?: 0) == least }.random(rng).also {
            used[it] = (used[it] ?: 0) + 1
            previous[group] = it
        }
    }

    /** [first]: greeting; [passportPending]: still waiting; [handover]: just received the passport or finished small talk. */
    fun next(cues: List<Cue>, cueFact: Int, covered: Set<Int>, passportPending: Boolean, first: Boolean,
             handover: Boolean, curt: Boolean): Move {
        fun move(prefix: String?, question: String, reask: Boolean = false): Move {
            lastQuestion = question
            topic = question.split('.').let { if (it[0] == "ask" || it[0] == "exact") it[1] else null }
            return Move(prefix, question, reask)
        }
        fun nextTopic() = topics.firstOrNull { topicFact(it) !in covered }
        fun ask(t: String?) = pick(if (t == null) "follow" else "ask.$t")
        if (first) return move(null, pick("greet"))
        if (passportPending) return move(null, pick(if (Cue.PASSPORT_2 in cues) "passport.why" else "passport.again"), reask = true)
        if (Cue.GLITCH in cues) return move(pick("glitch"), lastQuestion ?: ask(topic ?: nextTopic()), reask = true)
        val cue = cues.filter { it != Cue.PAUSE && it != Cue.PASSPORT_1 && it != Cue.PASSPORT_2 }.maxByOrNull { it.ordinal }
        val prefix = when (cue) {
            Cue.TRICK -> "trick"
            Cue.CONTRA_AGAIN -> "press.again"
            Cue.CONTRA_FIRST -> "press.first"
            Cue.WRONG_LANGUAGE -> "wronglang"
            Cue.UNCLEAR -> if (curt) "unclear.curt" else "unclear"
            Cue.ODD -> "odd"
            Cue.DODGE -> if (curt) "dodge.curt" else "dodge"
            Cue.SILENCE_2 -> if (curt) "silence.curt" else "silence.2"
            Cue.SILENCE_1 -> "silence.1"
            Cue.LOOK, Cue.TELL -> null
            else -> if (handover) "ack.start" else if (curt) "ack.curt" else "ack"
        }?.let { pick(it) }
        val contra = Cue.CONTRA_FIRST in cues || Cue.CONTRA_AGAIN in cues
        val reask = cues.any { it in setOf(Cue.TRICK, Cue.WRONG_LANGUAGE, Cue.UNCLEAR, Cue.ODD,
            Cue.DODGE, Cue.SILENCE_1, Cue.SILENCE_2) }
        val target = when {
            contra -> factTopic(cueFact)?.takeIf { it in topics && (cueFact != 1 || topic == "born") } ?: topic ?: nextTopic()
            Cue.TELL in cues || reask -> topic ?: nextTopic()
            else -> nextTopic()
        }
        val question = if ((contra || Cue.TELL in cues) && target != null) pick("exact.$target") else ask(target)
        return move(prefix, question, reask = reask && !contra && Cue.TELL !in cues && !handover)
    }
}
