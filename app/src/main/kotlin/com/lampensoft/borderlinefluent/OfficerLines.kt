fun topicFact(topic: String): Int = if (topic == "born") 1 else OFFICER_TOPICS.indexOf(topic) + 2

fun factTopic(fact: Int): String? = if (fact == 1) "born" else OFFICER_TOPICS.getOrNull(fact - 2)?.takeIf { it != "born" }

