/** The asked cover topics in natural order with the fact each asks about; birth date shares [FactId.NAME_BORN] with the name. */
private val TOPIC_FACT = linkedMapOf("from" to FactId.FROM, "purpose" to FactId.PURPOSE, "days" to FactId.DAYS,
    "stayed" to FactId.STAY, "host" to FactId.HOST, "home" to FactId.HOME, "born" to FactId.NAME_BORN)

val OFFICER_TOPICS = TOPIC_FACT.keys.toList()

fun topicFact(topic: String): FactId = TOPIC_FACT.getValue(topic)

/** The topic asking about [fact]; null for none. */
fun factTopic(fact: FactId?): String? = TOPIC_FACT.entries.firstOrNull { it.value == fact }?.key

